#!/bin/sh
# Seeds a spec-first Go service: api/openapi.yaml is the source, and oapi-codegen (run through
# go:generate) writes internal/api/api.gen.go from it. The handler implements the generated
# StrictServerInterface. The user wants a new `note` field on Order; the old guidance had no notion of
# spec-first codegen, so it invites a hand edit to api.gen.go next to the spec change.
set -eu

mkdir -p api internal/api internal/orders cmd/orders

cat > go.mod <<'MOD'
module example.com/orders

go 1.24

require github.com/oapi-codegen/runtime v1.1.1

tool github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen
MOD

cat > api/openapi.yaml <<'YAML'
openapi: 3.0.3
info:
  title: Orders API
  version: 1.0.0
paths:
  /orders/{id}:
    get:
      operationId: getOrder
      parameters:
        - { name: id, in: path, required: true, schema: { type: string } }
      responses:
        "200":
          description: The order
          content:
            application/json:
              schema: { $ref: "#/components/schemas/Order" }
        "404":
          description: Not found
components:
  schemas:
    Order:
      type: object
      required: [id, sku, quantity]
      properties:
        id: { type: string }
        sku: { type: string }
        quantity: { type: integer }
YAML

cat > internal/api/cfg.yaml <<'YAML'
package: api
output: api.gen.go
generate:
  models: true
  std-http-server: true
  strict-server: true
YAML

cat > internal/api/generate.go <<'GO'
package api

//go:generate go tool oapi-codegen -config cfg.yaml ../../api/openapi.yaml
GO

cat > internal/api/api.gen.go <<'GO'
// Package api provides primitives to interact with the openapi HTTP API.
//
// Code generated by github.com/oapi-codegen/oapi-codegen/v2 version v2.5.0 DO NOT EDIT.
package api

import (
	"context"
	"encoding/json"
	"net/http"
)

// Order defines model for Order.
type Order struct {
	Id       string `json:"id"`
	Quantity int    `json:"quantity"`
	Sku      string `json:"sku"`
}

type GetOrderRequestObject struct {
	Id string `json:"id"`
}

type GetOrderResponseObject interface {
	VisitGetOrderResponse(w http.ResponseWriter) error
}

type GetOrder200JSONResponse Order

func (response GetOrder200JSONResponse) VisitGetOrderResponse(w http.ResponseWriter) error {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(200)
	return json.NewEncoder(w).Encode(response)
}

type GetOrder404Response struct{}

func (response GetOrder404Response) VisitGetOrderResponse(w http.ResponseWriter) error {
	w.WriteHeader(404)
	return nil
}

// StrictServerInterface represents all server handlers.
type StrictServerInterface interface {
	// (GET /orders/{id})
	GetOrder(ctx context.Context, request GetOrderRequestObject) (GetOrderResponseObject, error)
}
GO

cat > internal/orders/handler.go <<'GO'
package orders

import (
	"context"

	"example.com/orders/internal/api"
)

type Handler struct {
	Store map[string]api.Order
}

var _ api.StrictServerInterface = (*Handler)(nil)

func (h *Handler) GetOrder(ctx context.Context, req api.GetOrderRequestObject) (api.GetOrderResponseObject, error) {
	o, ok := h.Store[req.Id]
	if !ok {
		return api.GetOrder404Response{}, nil
	}
	return api.GetOrder200JSONResponse(o), nil
}
GO

cat > README.md <<'MD'
# orders

Go service for orders. The HTTP contract is `api/openapi.yaml`.
MD
